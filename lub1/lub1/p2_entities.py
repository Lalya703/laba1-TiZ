# Корпачева Ульяна МТ-201: извлечение сущностей регулярными выражениями
# URL, e-mail, телефоны, даты, цены. Результаты хранятся отдельно по каждому типу.
import re

# порядок важен: e-mail и URL раньше остальных.
PAT = {
    "emails": re.compile(r"(?i)\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b"),
    "urls": re.compile(r"(?i)\b(?:https?://|www\.)[^\s|;,]+"),
    "phones": re.compile(
        r"(?<!\d)(?:\+7|8)[\s-]?\(?\d{3}\)?[\s-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}(?!\d)"),
    "dates": re.compile(
        r"(?<!\d)(?:\d{4}[-/.]\d{1,2}[-/.]\d{1,2}|\d{1,2}[-/.]\d{1,2}[-/.]\d{2,4})(?!\d)"),
    "prices": re.compile(
        r"(?i)(?:\d{1,3}(?:[ \u00a0]\d{3})+|\d{3,})(?:[.,]\d{1,2})?"
        r"\s*(?:₽|руб(?:лей)?|rub|р\.?|рубля)(?!\w)"),
}

def find_all(text):
    """Этап 3. Словарь {тип: [найденные значения]} из исходного текста."""
    return {k: p.findall(text) for k, p in PAT.items()}