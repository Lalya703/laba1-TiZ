# Шаблон "слово": одна или более букв (русские + латиница)
# Цифры и знаки не входят
WORD = re.compile(r"[А-Яа-яЁёA-Za-z]+")
# Шаблон маркеров вида [URL], [EMAIL], [PHONE], [DATE], [PRICE]
TAG = re.compile(r"\[[A-Z]+\]")


def split_words(text):
    """Этап 5. Достаём из текста только слова."""
    # сначала убираем маркеры (иначе WORD найдёт внутри [URL] кусок "URL"),
    # потом вытаскиваем все последовательности букв
    return WORD.findall(TAG.sub(" ", text))


def drop_stop(words):
    """Этап 5. Убираем стоп-слова и однобуквенные слова."""
    # оставляем слово, если его нет в STOP и длина больше 1
    # (регистр уже приведён к нижнему в p1.tidy, поэтому сравнение работает)
    return [w for w in words if w not in STOP and len(w) > 1]